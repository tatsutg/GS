function class:update(event)
    if not event.unit:isBreak() then
        self:HPTriggersCheck(event.unit)
    end
    event.unit:setReduceHitStop(self.GD.hitStop,1)---ヒットストップ無効or時止め無効
    self:charge(event.deltaTime)---チャージ
    self:countDown()
    return 1
end

---チャージ中のカウント
function class:charge(deltaTime)
    if self.isCharging then
        if self:chargeFail(self.gameUnit) then
            return;
        end
        self.count10 = self.count10 - deltaTime
        ---数秒ごとに奥義玉1つアップ
        if self.gameUnit:getBurstPoint() < 80 then
            self.count2 = self.count2 + deltaTime
            local chargeTime5 = self.chargeTime / 5
            if self.count2 > chargeTime5 then
                self.count2 = 0
                self.gameUnit:addSP(20)
            end
        end
        ---サブHPが時間内に0にならなかった場合の処理
        if self.count10 < 0 then
            ---奥義発動
            self.gameUnit:addSP(100)
            self.hpSkill = 2
            self.isCharging = false---チャージFLGオフ
        end
    end
end

function class:chargeFail(unit)
    local stun = unit:getTeamUnitCondition():findConditionValue(89);
    local paralyze = unit:getTeamUnitCondition():findConditionValue(91);
    local freeze = unit:getTeamUnitCondition():findConditionValue(96);
    if stun > 0 or paralyze > 0 or freeze > 0 or unit:isBreak() then
        self:showMessage(self.CHARGE_END_MESSAGE_LIST)
        self.gameUnit:takeAttack(1)
        self.gameUnit:setBurstPoint(0)
        self.isCharging = false---チャージFLGオフ
        self:execAddBuff(self.gameUnit,self.STUN_BUFF_LIST)
        return true
    end
    return false
end

function class:countDown()
    if BattleControl:get():getTime() > self.TIME_LIMIT then
        local myTeam = megast.Battle:getInstance():getTeam(true);
        for i = 0,6 do
            local myTeamUnit = myTeam:getTeamUnit(i)
            if myTeamUnit ~= nil then
                myTeamUnit:setHP(0)
                myTeam:deadUnit(myTeamUnit:getIndex());
            end
        end
    end
end


    ---ターゲット指定
    for i = 0,3 do
        local myTeamUnit = myTeam:getTeamUnit(i)
        if myTeamUnit ~= nil then
            if args.arg == target:getIndex() then
                self.targetUnitIndex = args.arg
            end
        end
    end
    return 1
end

----// takeBreakeDamageValue //-----------------------------------------------------------------------------

-- update
---------------------------------------------------------------------------------
function class:update(event)
    self:HPTriggersCheck(event.unit)
    event.unit:setReduceHitStop(100,1)---ヒットストップ無効or時止め無効
    local hpRate = summoner.Utility.getUnitHealthRate(event.unit) * 100;
    if hpRate >= 20 then
        self:initSkillWeight({DEFAULT = 100})
    else
        self:initSkillWeight({HP20 = 100})
    end
    if self.posX == nil then
        self.posX = event.unit:getPositionX()
        self.posY = event.unit:getPositionY()
    else
        event.unit:setPositionX(self.posX)
        event.unit:setPositionY(self.posY)
    end
    return 1
end


function class:setTriggerList()
    self.TIME_UP_ID = 2
    self.TRIGGERS = {
        [1] = {
            tag = "HP_FLG",
            action = function (status) self:hp30(status) end,
            HP = 30,
            used = false
        },
        [self.TIME_UP_ID] = {
            tag = "TIME_UP",
            action = function (status) self:timeUp(status) end,
            used = false
        }
    }
    self.HP_TRIGGERS = {}
    self.hpMarkers = {}
    for index,trigger in pairs(self.TRIGGERS) do
        if trigger.tag == "HP_FLG" then
            self.HP_TRIGGERS[index] = trigger
            self.hpMarkers[self.TRIGGERS[index].HP] = self.gameUnit:addNumHpMarker(self.TRIGGERS[index].HP * 0.01)
        end
    end
end

function class:hp30(status)
    if status == "use3" then
        self.stateName = "FURY"
        self.isRage = true
        self.saveBP = self.gameUnit:getBurstPoint()
        self.gameUnit:addSP(100)
        self.invincibleFLG = true
        self.gameUnit:setInvincibleTime(30)
        self:execAddBuff(self.gameUnit,self.BUFF_LIST)
        if self.isZetsu then
            self:execAddBuff(self.gameUnit,self.BUFF_LIST2)
        end
        self:removeAllBadstatus(self.gameUnit) ---状態異常全除去
        self:execAddBuff(self.gameUnit,self.ANTI_BAD_CONDITION_BUFF_LIST)
        self:showMessage(self.HP30_MESSAGE_LIST)
    end
end

function class:timeUp(status)
    if status == "use3" then
        self:showMessage(self.TIMEUP_BUFF_MESSAGE_LIST)
        self:execAddBuff(self.gameUnit,self.TIMEUP_BUFF_BOX_LIST[1])
        self:execAddBuff(self.gameUnit,self.TIMEUP_BUFF_BOX_LIST[2])
    end
end


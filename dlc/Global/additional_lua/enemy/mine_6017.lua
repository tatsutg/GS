-- takeSkill
---------------------------------------------------------------------------------
function class:takeSkill(event)
    if not self.skillCheckFlg and megast.Battle:getInstance():isHost() then
        self.skillCheckFlg = true;
        return self:skillReroll(event.unit);
    end

    if not megast.Battle:getInstance():isHost() and not self.fromHost then
        event.unit:takeIdle();
        return 0;
    end

    if event.index == 2 and self.isRage then
        self.isRage = false
    elseif event.index == 3 and self.isFury then
        self.isFury = false
    end
    self.skillCheckFlg = false;
    self.afterSkillFLG = true;
    self.fromHost = false;
    self:skillActiveSkillSetter(event.unit,event.index);
    return 1
end


function class:skillReroll(unit)
    local skillIndex = self:getSkillIndex()

    if self.isRage then
        skillIndex = 2
    elseif self.isFury then
        skillIndex = 3
    else
        if self.bugCheckFLG then summoner.Utility.messageByEnemy(self.STATE_SKILL.actCount,7,Color.magenta); end
        self:movePatternState(self.SKILL_SET_LIST,self.STATE_SKILL)
    end
    unit:takeSkill(skillIndex);
    megast.Battle:getInstance():sendEventToLua(self.scriptID,2,skillIndex);
    return 0;
end

----// takeDamageValue //-----------------------------------------------------------------------------
-- スキップ不可
---------------------------------------------------------------------------------
function class:takeDamageValue(event)
    if self.invincibleFLG then return 0 end
    if not self:findBlindCondition(event.unit) then
        event.value = event.value * self.damageRate
    end
    if self:isRaceTypeX(event.enemy,1) then
        event.value = event.value * self.damageRate
    end
    event.value = self:adjustHpFlg(event.unit,event.value)
    return event.value
end


function class:adjustHpFlg(unit,value)
    local anotherHp = unit:getHP() - value
    for _,trigger in pairs(self.HP_TRIGGERS) do
        local stopBorder = self.gameUnit:getCalcHPMAX() * trigger.HP * 0.01
        if not trigger.used and stopBorder >= anotherHp then
            self:refresh(self.gameUnit) ---停止系状態異常除去(このタイミングでないとたまにバグる)
        return self:calcDamageValue(unit,stopBorder,value)
        end
    end

    return value
end

function class:calcDamageValue(unit,border,value)
    self.breakSkip = true
    return unit:getHP() - border + 1
end

function class:findBlindCondition(unit)
    local cnt = 0;
    if unit:getTeamUnitCondition():findConditionValue(93) > 0 then
        return true;
    end
    return false;
end

function class:isRaceTypeX(unit,x)
    if unit:getRaceType() == x then
        return true;
    end
    if unit:getParentTeamUnit() ~= nil then
        if unit:getParentTeamUnit():getRaceType() == x then
            return true;
        end
    end
    return false;
end

function class:BPReverse(unit)
    unit:getTeamUnitCondition():StopConditionDataEntirely(10)
    ---バフ設定
    local MINUS_BP_BUFF_LIST = {}
    local conditionSize = unit:getTeamUnitCondition():getAllConditionsSize();
    local condCount = 0
    local workCount = 0
    if conditionSize ~= 0 then
        for i = 0,(conditionSize - 1) do
            local cond = unit:getTeamUnitCondition():getAllConditionsAt(i);
            if cond ~= nil then
                if cond:getConditionTypeAsInt() == 10 then
                    if cond:getValue() > 0 then
                        if cond:getGroupID() ~= 0 then
                            ---バフリスト作成
                            MINUS_BP_BUFF_LIST[i] = {
                                ID = 0,
                                BUFF_ID = 10,
                                VALUE = cond:getValue() * -1, ---valueマイナス化
                                DURATION = 30,
                                ICON = 213,
                                GROUP_ID = cond:getGroupID(),---グループIDセット
                                PRIORITY = cond:getPriority() * 100 ---優先度100倍
                            }
                        else
                            ---バフリスト作成
                            MINUS_BP_BUFF_LIST[i] = {
                                ID = 0,
                                BUFF_ID = 10,
                                VALUE = cond:getValue() * -1, ---valueマイナス化
                                DURATION = 30,
                                ICON = 213
                            }
                        end
                        cond:setValue(0) ---バフ無効化
                        cond:setTime(0) ---バフ除去
                        workCount = workCount + 1
                        if cond:getScriptID() == 337 then
                            unit:getTeamUnitCondition():addCondition(self.abilityStopFLG,0,0,99999,0)---バフ全体化停止用FLG
                        end
                    end
                end
                ---ループ回避
                condCount = condCount + 1
                if condCount > 100 then
                    break
                end
            end
        end
    end
    ---逆転バフ付与
    for index,buffList in pairs(MINUS_BP_BUFF_LIST) do
        self:execAddBuff(unit,MINUS_BP_BUFF_LIST[index])
    end
    return workCount
end


-- update
---------------------------------------------------------------------------------
function class:update(event)
    self:hpTriggersCheck(event.unit)
    event.unit:setReduceHitStop(self.GD.hitStop,1)---ヒットストップ無効or時止め無効
    ---アビリティ
    --self:addAbilityBuff(self.ABILITY_BUFF_LIST[1])
    ---バトルタイム
    self:countDown()

    --攻撃中か確認
    if self.attack3Flg and event.unit:getUnitState() ~= kUnitState_attack then
        self.attack3Flg = false
    end

    ---奥義チャージ
    if self.chargeFlg then
        self.battleTime = self.battleTime + event.deltaTime
        if self.battleTime >= self.GD.addSpTime then
            self.battleTime = 0
            event.unit:addSP(20);
        end

        --気絶 or ブレイク
        local cond = event.unit:getTeamUnitCondition():findConditionWithType(89);
        if cond ~= nil or event.unit:isBreak() then
            self.chargeFlg = false
            event.unit:setBurstPoint(0)
            self:execAddBuff(event.unit,self.BUFF_LIST[2])
            event.unit:takeIdle()
            event.unit:takeAnimation(0,"idle",false);
            self:showMessage(self.CHARGE_OFF_MESSAGE_LIST)
        end
    end
    return 1
end

function class:addAbilityBuff(buffBox)
    local myTeam = megast.Battle:getInstance():getTeam(true);
    for i = 0, 6 do
        local myTeamUnit = myTeam:getTeamUnit(i)
        if myTeamUnit ~= nil then
            local buff = myTeamUnit:getTeamUnitCondition():findConditionWithID(buffBox.ID)
            if buff == nil then
                self:execAddBuff(myTeamUnit,buffBox)
            end
        end
    end
end

function class:countDown()
    if BattleControl:get():getTime() > self.GD.timeLimit then
        local myTeam = megast.Battle:getInstance():getTeam(true);
        for i = 0,6 do
            local myTeamUnit = myTeam:getTeamUnit(i)
            if myTeamUnit ~= nil then
                myTeamUnit:setHP(0)
                myTeam:deadUnit(myTeamUnit:getIndex());
            end
        end
    end
end


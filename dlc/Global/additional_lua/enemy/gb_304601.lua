function class:attackDamageValue(event)
    local enemyUnit = self:getAncestorUnit(event.enemy)
    if self.attack3Flg and self.unitFlgTbl[enemyUnit:getIndex()] then
        self.unitFlgTbl[enemyUnit:getIndex()] = false
        self:attackBuffCheck(self.ATTACK_BUFF_LIST[1],enemyUnit:getIndex())
    end

    local gbHatePercent = event.unit:getGBHatePercent(enemyUnit:getIndex())
    local rate = ((gbHatePercent * self.GD.hateGimmickRate) + self.GD.hateGimmickBase) / 100
    --summoner.Utility.messageByEnemy(gbHatePercent.."/"..rate)
    event.value = event.value * rate
    return event.value
end

function class:attackBuffCheck(buffBox,index)
    local flg = false
    local rand = math.random(0,100)
    local par = self.GD.attackBuff_89_1 + self.gbAreaNumber * self.GD.attackBuff_89_2
    if par >= rand then
        flg = true
    end

    if flg then
        local myTeam = megast.Battle:getInstance():getTeam(true);
        for i = 0, 6 do
            local myTeamUnit = myTeam:getTeamUnit(i)
            if myTeamUnit ~= nil then
                if myTeamUnit:getIndex() == index then
                    self:execAddBuff(myTeamUnit,buffBox)
                end
            end
        end
    end
end


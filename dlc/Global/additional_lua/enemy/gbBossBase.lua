function class:start(event)
    self.GD = summoner.Utility.getGimmickJsonData(event.unit, {
        addSP = 5,
        attackDelay = -1,
        hitStop = 0,
        targetCondition = 90,
        startBuffType = 0,
        startBuffValue = 0,
        startBuffScriptID = 0,
        startBuffValue1 = 0,
        startBuffValue2 = 0,
        startBuffIcon = 0,
        startBuffTime = 99999,
        startBuffTimer = 20
    })
    self:dump(self.GD)
    self.fromHost = false;
    self.gameUnit = event.unit;
    --------------------------------
    self.spValue = self.GD.addSP;---addSPの量
    if self.GD.attackDelay ~= -1 then
        event.unit:setAttackDelay(self.GD.attackDelay);---アタックディレイ
    end
    --event.unit:addSP(40)---戦闘開始時の奥義ゲージ量
    --------------------------------
    self.attackCheckFlg = false;
    self.skillCheckFlg = false;
    self.afterSkillFLG = false;

    event.unit:setSPGainValue(0);
    event.unit:setSkillInvocationWeight(0);

    self.isRage = false
    self.isFury = false

    self:setMessageBoxList()
    self:setTriggerList()
    self:setBuffBoxList()

    self:initAttackWeight({DEFAULT = 100})
    self:initSkillWeight({DEFAULT = 100})

    self.stateName = "NORMAL"

    self.breakSkip = true

    self.hpSkill = 0

    self.saveBP = 0

    self.timer = self.GD.startBuffTimer

    if self.START_MESSAGE_LIST[self.GD.targetCondition] ~= nil then
        self:execShowMessage(self.START_MESSAGE_LIST[self.GD.targetCondition])
    end
    self:GB_start(event)
    return 1
end


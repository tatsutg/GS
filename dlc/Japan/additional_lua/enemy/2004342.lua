        self.gameUnit:setInvincibleTime(6)

        self.gameUnit:takeItemSkill(0) --吹雪
        self.item:setCoolTimer(0)
        self.gameUnit:takeAnimation(0,"attack5",false)
        self.spValue = 30;

        self:execAddBuff(self.gameUnit,self.HP60_BUFF)
        self:glabEnd(self.gameUnit)
    end
end


function class:update(event)
    self:hpTriggersCheck(event.unit)
    event.unit:setReduceHitStop(self.GD.hitStop,1)---ヒットストップ無効or時止め無効

    ---HPトリガーで飛行状態に移行
    if not self.isFlying and event.unit:getUnitState() == kUnitState_skill then
        self.isFlying = true
        self:initAttackWeight({WING = 100})
        self.spValue = self.GD.addSP;---addSPの量
        self:execAddBuff(event.unit,self.BUFF_BOX_LIST[2])  --氷結耐性
        self:execAddBuff(event.unit,self.BUFF_BOX_LIST[3])  --氷結回避率
        event.unit:getTeamUnitCondition():removeConditionWithID(self.BUFF_BOX_LIST[7].ID)
    end
    ---氷結状態で着地
    if self:findFreezeCondition(event.unit) and self.isFlying then
        self:fall(event.unit)
    end
    self:countDown()
    return 1
end

function class:findFreezeCondition(unit)
    local cnt = 0;
    local badStatusList = { 96 }
    for k,v in pairs(badStatusList) do
        if unit:getTeamUnitCondition():findConditionValue(v) > 0 then
            return true;
        end
    end
    return false;
end

function class:fall(unit)
    self.isFlying = false
    self.takeOffFLG = false
    self.hpSkillFLG = false
    unit:setBurstPoint(0)
    self.spValue = 0;---addSPの量
    --unit:setAttackDelay(10);---アタックディレイ
    self:initAttackWeight({DEFAULT = 100})
    self:execAddBuff(unit,self.BUFF_BOX_LIST[1])  --気絶
    self:execAddBuff(unit,self.BUFF_BOX_LIST[7])
end

function class:countDown()
    if BattleControl:get():getTime() > self.TIME_LIMIT then
        local myTeam = megast.Battle:getInstance():getTeam(true);
        for i = 0,6 do
            local myTeamUnit = myTeam:getTeamUnit(i)
            if myTeamUnit ~= nil then
                myTeamUnit:setHP(0)
                myTeam:deadUnit(myTeamUnit:getIndex());
            end
        end
    end
end


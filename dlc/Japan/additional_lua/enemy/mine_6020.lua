end

function class:checkConditionCount(condType)
    local myTeam = megast.Battle:getInstance():getTeam(true);
    local count = 0
    for i = 0,6 do
        local myTeamUnit = myTeam:getTeamUnit(i)
        if myTeamUnit ~= nil then
            local conditionSize = myTeamUnit:getTeamUnitCondition():getAllConditionsSize();
            if conditionSize == 0 then return 0 end
            for i = 0,(conditionSize - 1) do
                local cond = myTeamUnit:getTeamUnitCondition():getAllConditionsAt(i);
                if cond ~= nil then
                    if cond:getValue() > 0 then
                        if cond:getConditionTypeAsInt() == condType then
                            count = count + 1
                        end
                    end
                end
            end
        end
    end
    return count
end



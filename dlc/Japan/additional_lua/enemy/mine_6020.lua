function class:update(event)
    self:HPTriggersCheck(event.unit)
    event.unit:setReduceHitStop(100,1)---ヒットストップ無効or時止め無効

    ---ブレイク値減少対象にフラグバフを付与
    local myTeam = megast.Battle:getInstance():getTeam(true);
    for i = 0,6 do
        local myTeamUnit = myTeam:getTeamUnit(i)
        if myTeamUnit ~= nil then
            local cond = myTeamUnit:getTeamUnitCondition():findConditionWithID(self.BREAK_GUARD_BUFF_LIST.ID)
            if cond == nil then
                self:execAddBuff(myTeamUnit,self.BREAK_GUARD_BUFF_LIST)
            end
        end
    end
    if self.breakFLG and not event.unit:isBreak() and self.breakCount <= 5 then
        self.breakFLG = false
        self:showMessage(self.BREAK_END_MESSAGE_LIST)
    end
    ---燃焼判定
    local burnCond = event.unit:getTeamUnitCondition():findConditionWithType(97)
    if burnCond == nil then
        local cond = event.unit:getTeamUnitCondition():findConditionWithID(self.BREAK_GUARD_BUFF_LIST.ID)
        if cond == nil then
            self:execAddBuff(event.unit,self.BREAK_GUARD_BUFF_LIST)
        end
    else
        local cond = event.unit:getTeamUnitCondition():findConditionWithID(self.BREAK_GUARD_BUFF_LIST.ID)
        if cond ~= nil then
            event.unit:getTeamUnitCondition():removeConditionWithID(self.BREAK_GUARD_BUFF_LIST.ID)
        end
    end
    ---死亡時処理
    if megast.Battle:getInstance():getBattleState() == kBattleState_active then
        if self.lastSkillFLG == nil then self.lastSkillFLG = false end
        if self.lastSkillFLG and event.unit:getUnitState() ~= kUnitState_skill then
            event.unit:getTeam():deadUnit(event.unit:getIndex());
            megast.Battle:getInstance():waveEnd(true);
        end
        if self.TRIGGERS[2].used then
            if self.deadCount == nil then self.deadCount = 0 end
            self.deadCount = self.deadCount + event.deltaTime
            if self.deadCount >= 15 then
                event.unit:getTeam():deadUnit(event.unit:getIndex());
                megast.Battle:getInstance():waveEnd(true);
            end
        end
    end
    self:setTimeUp()
    return 1
end


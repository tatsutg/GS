function class:takeDamageValue(event)
    if self:checkConditionCount(96) < 4 then
        event.value = event.value * self.freezeRate[self:checkConditionCount(96)]
    else
        event.value = 1
    end
    if self.breakCount < 5 then
        event.value = event.value * self.damageRate[self.breakCount]
    else
        local floatNum = (self.breakCount - 4) / 10
        event.value = event.value * (self.damageRate[4] + floatNum)
    end

    event.value = self:adjustHpFlg(event.unit,event.value)
    return event.value
end

function class:adjustHpFlg(unit,value)
    local anotherHp = unit:getHP() - value
    for _,trigger in pairs(self.HP_TRIGGERS) do
        local stopBorder = self.gameUnit:getCalcHPMAX() * trigger.HP * 0.01
        if not trigger.used and stopBorder >= anotherHp then
            self:refresh(self.gameUnit) ---停止系状態異常除去(このタイミングでないとたまにバグる)
        return self:calcDamageValue(unit,stopBorder,value)
        end
    end

    return value
end

function class:calcDamageValue(unit,border,value)
    self.breakSkip = true
    return unit:getHP() - border + 1
end

----// takeBreakeDamageValue //-----------------------------------------------------------------------------
-- 条件 : 被ダメージ時。
-- 引数 : event.unit / 自ユニット  event.enemy / 攻撃者  event.value / 被ブレイクダメージ量
---------------------------------------------------------------------------------
function class:takeBreakeDamageValue(event)
    if self.breakCount < 5 then
        event.value = event.value * self.breakRate[self.breakCount]
    else
        event.value = event.value * self.breakRate[5]
    end

    local burnCond = event.unit:getTeamUnitCondition():findConditionWithType(97)
    local sickCond = event.unit:getTeamUnitCondition():findConditionWithType(94)
    if burnCond ~= nil or sickCond ~= nil then
        event.value = event.value * self.breakDamageNoBuffRate
    else
        event.value = event.value * self.breakDamageOnBuffRate
    end

    if self.breakSkip then
        self.breakSkip = false
        return 0
    end
    return event.value
end

----// takeBreake //-----------------------------------------------------------------------------
-- 条件 : トリガー条件に到達する攻撃を受けた際、ブレイクしない(スキップ不可が必要)
---------------------------------------------------------------------------------
function class:takeBreake(event)
    for i = 1,table.getn(self.HP_TRIGGERS) do
        local stopBorder = self.gameUnit:getCalcHPMAX() * self.HP_TRIGGERS[i].HP * 0.01
        if event.unit:getHP() <= stopBorder and event.unit:getHP() > stopBorder - 2 then
            return 0
        end
    end
    self:showMessage(self.BREAK_MESSAGE_LIST)
    self.gameUnit:removeNumBreakBadge()
    self.breakCount = self.breakCount + 1
    self.breakFLG = true
    return 1
end


    unit:addSP(self.spValue);
    return 1;
end

function class:attackSummon(unit,friendCount)
    if friendCount < 6 then
        local rand = math.random(1,2);
        if rand == 1 then
            self:MultipleSummon(unit,self.summonUnitID1,1);
            --self:showMessage(self.SUMMON_MESSAGE_LIST);
            self:showMessage(self.SUMMON1_MESSAGE_LIST);
        else
            self:MultipleSummon(unit,self.summonUnitID2,1);
            --self:showMessage(self.SUMMON_MESSAGE_LIST);
            self:showMessage(self.SUMMON2_MESSAGE_LIST);
        end
    end
    self:findFriend();
end


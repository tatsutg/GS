-- takeSkill
---------------------------------------------------------------------------------
function class:takeSkill(event)
    if not self.skillCheckFlg and megast.Battle:getInstance():isHost() then
        self.skillCheckFlg = true;
        return self:skillReroll(event.unit);
    end

    if not megast.Battle:getInstance():isHost() and not self.fromHost then
        event.unit:takeIdle();
        return 0;
    end

    if event.index == 2 then
        if self.spValue < 50 then
            self.spValue = self.spValue + 10
            self:showMessage(self.SKILL2_1_MESSAGE_LIST)
        else
            self:showMessage(self.SKILL2_2_MESSAGE_LIST)
        end
        self:execAddBuff(event.unit,self.BUFF_BOX_LIST[1])
        ---召喚ギミック
        local num = self:summonNumCalc(event.unit)
        local summonCount = 1
        if LuaUtilities.rand(1,101) > num then
            summonCount = 2
        end
        local rate = self:summonRateCalc(event.unit)
        if LuaUtilities.rand(1,101) <= rate then
            for i = 1, summonCount do
                self:summon(event.unit,2005543)
            end
        else
            for i = 1, summonCount do
                self:summon(event.unit,2005544)
            end
        end
    end

    self.skillCheckFlg = false;
    self.cutInFLG = false
    self.addSpSkipFLG = true ---スキル直後の通常攻撃ではaddSPしない
    self.fromHost = false;
    self:skillActiveSkillSetter(event.unit,event.index);
    --self:initAttackWeight({DEFAULT = 100})---奥義使用後はリセットでスキル1からスタート
    return 1
end


function class:skillReroll(unit)
    local skillIndex = self:getSkillIndex()

    if self.hpSkill ~= 0 then
        skillIndex = self.hpSkill
        self.hpSkill = 0
    else
        self:movePatternState(self.SKILL_SET_LIST,self.STATE_SKILL)
    end

    if self.cutInSkill[skillIndex] ~= nil then
        unit:takeSkillWithCutin(tonumber(skillIndex),self.cutInSkill[skillIndex]);
    else
        unit:takeSkill(tonumber(skillIndex));
    end
    megast.Battle:getInstance():sendEventToLua(self.scriptID,2,tonumber(skillIndex));
    return 0;
end

function class:takeSkillFromHost(unit,index)
    self.fromHost = true;
    if self.cutInSkill[index] ~= nil then
        unit:takeSkillWithCutin(index,self.cutInSkill[index]);
    else
        unit:takeSkill(index);
    end
end

---特定enemyIdの味方数をカウント
function class:teamCountLimited(unit,id)
    local myTeam = unit:getTeam();
    local count = 0
    for i = 0, 6 do
        local myTeamUnit = myTeam:getTeamUnit(i)
        if myTeamUnit ~= nil then
            if myTeamUnit:getEnemyID() == id then
                count = count + 1
            end
        end
    end
    return count
end
---召喚数確率を計算
function class:summonNumCalc(unit)
    local angel1 = self:teamCountLimited(unit,2005543)
    local angel2 = self:teamCountLimited(unit,2005544)
    if (angel1 + angel2) == 0 then
        return 0
    elseif (angel1 + angel2) == 1 then
        return 20
    elseif (angel1 + angel2) == 2 then
        return 80
    else
        return 100
    end
end
---召喚割合を計算
function class:summonRateCalc(unit)
    local angel1 = self:teamCountLimited(unit,2005543)
    local angel2 = self:teamCountLimited(unit,2005544)
    if angel1 == angel2 then
        return 50
    elseif angel1 > angel2 then
        return 30
    else
        return 70
    end
end


function class:takeSkill(event)
    if not self.skillCheckFlg and megast.Battle:getInstance():isHost() then
        self.skillCheckFlg = true;
        return self:skillReroll(event.unit);
    end

    if not megast.Battle:getInstance():isHost() and not self.fromHost then
        event.unit:takeIdle();
        return 0;
    end

    if event.index == 1 then
        self:stunSpecial(event.unit)
        local buff = self:execAddBuff(event.unit,self.BUFF_BOX_LIST[4])
        buff:setRemoveOnResetState(true);
    elseif event.index == 2 then
        self:execAddBuff(event.unit,self.BUFF_BOX_LIST[2])
    elseif event.index == 3 then
        self:stun(event.unit)
        self.afterSkill = 3
        self.lastSkillFLG = true
    end
    
    self.skillCheckFlg = false;
    self.afterSkillFLG = true;
    self.fromHost = false;
    self:skillActiveSkillSetter(event.unit,event.index);
    return 1
end


function class:skillReroll(unit)
    local skillIndex = self:getSkillIndex()

    if self.hpSkill ~= 0 then
        skillIndex = self.hpSkill
        self.hpSkill = 0
    else
        self:movePatternState(self.SKILL_SET_LIST,self.STATE_SKILL)
    end

    if self.cutInSkill[skillIndex] ~= nil then
        unit:takeSkillWithCutin(tonumber(skillIndex),self.cutInSkill[skillIndex]);
    else
        unit:takeSkill(tonumber(skillIndex));
    end
    megast.Battle:getInstance():sendEventToLua(self.scriptID,2,tonumber(skillIndex));
    return 0;
end

function class:takeSkillFromHost(unit,index)
    self.fromHost = true;
    if self.cutInSkill[index] ~= nil then
        unit:takeSkillWithCutin(index,self.cutInSkill[index]);
    else
        unit:takeSkill(index);
    end
end

function class:stun(unit)
    local x = unit:getPositionX();
    local y = unit:getPositionY();
    local myTeam = megast.Battle:getInstance():getTeam(true);
    for i = 0, 6 do
        local myTeamUnit = myTeam:getTeamUnit(i)
        if myTeamUnit ~= nil then
            self:execAddBuff(myTeamUnit,self.BUFF_BOX_LIST[1])
            myTeamUnit:setPosition((x + 480 + math.random(-50,50)),(y + math.random(-50,50)))
        end
    end
    return 1
end

function class:stunSpecial(unit)
    local x = unit:getPositionX();
    local y = unit:getPositionY();
    local myTeam = megast.Battle:getInstance():getTeam(true);
    for i = 0, 6 do
        local myTeamUnit = myTeam:getTeamUnit(i)
        if myTeamUnit ~= nil then
            if megast.Battle:getInstance():isHost() then
                local damageValue = self.damageBox[i]/self:sumDamageBox()
                self.BUFF_BOX_LIST[3].DURATION = 6 + ( (1 + ( 10 * damageValue ) ) ^ 2)
                self:execAddBuff(myTeamUnit,self.BUFF_BOX_LIST[3])
                myTeamUnit:setPosition((x + 480 + math.random(-50,50)),(y + math.random(-50,50)))
                megast.Battle:getInstance():sendEventToLua(self.scriptID,5,((math.floor(self.BUFF_BOX_LIST[3].DURATION))*10)+i);
            end
        end
    end
    for i = 0,6 do
        self.damageBox[i] = 0
    end
    return 1
end

function class:sumDamageBox()
    local damageValue = 0
    for i = 0,6 do
        damageValue = damageValue + self.damageBox[i]
    end
    return damageValue
end


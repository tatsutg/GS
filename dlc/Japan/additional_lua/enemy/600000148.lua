function class:getGimmickDefault()
    return {
        ---基本
        addSP = 0,                  --SP獲得量
        attackDelay = 4,            --アタックディレイ
        hitStop = 100,              --ヒットストップ・時止め無効

        ---被ダメージ補正（[dmgRateBase + dmgRateAdd × 状態異常の種類数]倍。上限 dmgRateMax、1未満のダメージは1）
        dmgRateBase = 0.05,         --状態異常が無いときの倍率
        dmgRateAdd = 0.5,           --状態異常1種類ごとに加算する倍率
        dmgRateMax = 2.0,           --倍率の上限
    };
end

---------------------------------------------------------------------------------
-- start
---------------------------------------------------------------------------------
function class:start(event)
    self.GD = summoner.Utility.getGimmickJsonData(event.unit, self:getGimmickDefault());
    self:dump(self.GD);

    self.fromHost = false;
    self.gameUnit = event.unit;
    --------------------------------
    self.spValue = self.GD.addSP;---addSPの量
    if self.GD.attackDelay > 0 then
        event.unit:setAttackDelay(self.GD.attackDelay);---アタックディレイ
    end
    --------------------------------
    self.attackCheckFlg = false;
    self.skillCheckFlg = false;
    self.afterSkillFLG = false;
    self.cutInFLG = false;
    event.unit:setSPGainValue(0);
    event.unit:setSkillInvocationWeight(0);

    self:setMessageBoxList();
    self:setTriggerList();

    self:initAttackWeight({DEFAULT = 100});
    self:initSkillWeight({DEFAULT = 100});

    self.stateName = "NORMAL";
    self.breakSkip = true;
    self.hpSkill = 0;
    self.saveBP = 0;
    self.breakFlg = false;
    self.hpSkillFLG = false;
    return 1;
end


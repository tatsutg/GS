function class:takeDamageValue(event)
    event.value = self:calcStatusDamage(event.unit,event.value);
    event.value = self:adjustHpFlg(event.unit,event.value);
    return event.value;
end

----// takeMultiDamageValue //-----------------------------------------------------------------------------
-- マルチ用（レイドでは呼ばれない）
---------------------------------------------------------------------------------
function class:takeMultiDamageValue(event)
    if event.unit:getInvincibleTime() > 0 then
        event.value = 0;
    else
        event.value = self:calcStatusDamage(event.unit,event.value);
    end
    event.value = self:adjustHpFlg(event.unit,event.value);
    return event.value;
end

---全てのダメージに補正。毒・暗闇・病気・燃焼の種類が多いほど被ダメージアップ
function class:calcStatusDamage(unit,value)
    local rate = self.GD.dmgRateBase + self.GD.dmgRateAdd * self:countBadStatus(unit);
    if rate > self.GD.dmgRateMax then
        rate = self.GD.dmgRateMax;
    end
    value = value * rate;
    if value < 1 then
        value = 1;
    end
    return value;
end

---かかっている状態異常の種類数（同じ種類が重複しても1と数える）
function class:countBadStatus(unit)
    local count = 0;
    for _,types in ipairs(self.BAD_STATUS_TYPES) do
        for _,type in ipairs(types) do
            if unit:getTeamUnitCondition():findConditionWithType(type) ~= nil then
                count = count + 1;
                break;
            end
        end
    end
    return count;
end

function class:adjustHpFlg(unit,value)
    local anotherHp = unit:getHP() - value;
    for _,trigger in pairs(self.HP_TRIGGERS) do
        local stopBorder = self.gameUnit:getCalcHPMAX() * trigger.HP * 0.01;
        if not trigger.used and stopBorder >= anotherHp then
            self:refresh(self.gameUnit); ---停止系状態異常除去(このタイミングでないとたまにバグる)
            return unit:getHP() < stopBorder and 1 or self:calcDamageValue(unit,stopBorder,value);
        end
    end
    return value;
end

function class:calcDamageValue(unit,border,value)
    self.breakSkip = true;
    return unit:getHP() - border + 1;
end

